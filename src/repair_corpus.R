# =============================================================================
# src/repair_corpus.R - regenerate the handful of rows the API dropped (A1)
# =============================================================================
# A 50k-request run over a shared endpoint will lose a few. Ours lost 25
# (0.05%), scattered randomly across 18 topics and all 5 ratings - so they are
# transport failures, not a systematic bias.
#
# Dropping them would be fine statistically. We regenerate instead, because it
# costs seconds and it means the shipped artifact has an exactly balanced design
# (2000 per topic, 10000 per rating) rather than one that is balanced "apart
# from 25 rows I have to explain in a footnote".
#
#   Rscript src/repair_corpus.R
# =============================================================================

source("config.R"); source("src/api_client.R"); source("src/gen_prompts.R")
suppressPackageStartupMessages({ library(readr); library(dplyr) })

design <- load_design()
in_f  <- "data/big/reviews_raw.csv.gz"
out_f <- "data/big/reviews.csv.gz"

d <- read_csv(in_f, show_col_types = FALSE)
cat("loaded", nrow(d), "rows from", in_f, "\n")

bad <- which(is.na(d$text) | trimws(d$text) == "")
cat("rows needing repair:", length(bad), "\n")

if (length(bad)) {
  # Rebuild the exact prompts for the failed rows from their text_id, so the
  # repaired rows are generated by the same design as everything else.
  all_prompts <- make_prompts(n_replicates = design$full_corpus$n_replicates_per_cell,
                              design = design)
  need <- all_prompts[match(d$text_id[bad], all_prompts$text_id), ]
  stopifnot(!any(is.na(need$text_id)))

  cat("regenerating ...\n")
  txt <- chat_many(need$user_prompt, system = need$system_prompt[1],
                   temperature = design$generation$temperature,
                   max_tokens  = design$generation$max_tokens,
                   seed = need$seed + 1L,   # nudge the seed: the original seed
                                            # already failed, and an identical
                                            # request could return a cached miss
                   progress = FALSE)
  d$text[bad] <- txt
  cat("still failing after retry:", sum(is.na(txt)), "\n")
}

# ---- final acceptance gate --------------------------------------------------
d <- d |> filter(!is.na(text), trimws(text) != "")
n_dup <- sum(duplicated(d$text))
if (n_dup > 0) {
  cat("dropping", n_dup, "exact duplicates\n")
  d <- d[!duplicated(d$text), ]
}

write_csv(d, out_f)
cat("\n=== FINAL ===\n")
cat("rows      :", nrow(d), "\n")
cat("empty     :", sum(is.na(d$text) | trimws(d$text) == ""), "\n")
cat("duplicates:", sum(duplicated(d$text)), "\n")
cat("per topic : min", min(table(d$topic)), "max", max(table(d$topic)), "\n")
cat("per rating:", paste(table(d$rating), collapse = " "), "\n")
cat("wrote", out_f, sprintf("(%.1f MB)", file.size(out_f)/1e6), "\n")
